"""План збірки ядра на спині — від «нічого нема» до «світить на плайї».

Що це. Генератор `lights/data/back_core_install.json`: вісім етапів і шість
перевірок, кожен етап із ознакою закриття («зроблено, коли…»), ризиком і
посиланням на місце в базі, звідки взяті його числа. Сторінку з нього збирає
site/build.py у таблицю «План робіт».

Чому генератор, а не написаний руками JSON. У плані тридцять із гаком чисел, і
майже всі вони поки живі: крок 5 прямо каже замінити прикидку «світиться 25%»
заміряним числом. Щойно це станеться, «9.3 Вт», «75 Wh» і саме «25%» у тексті
плану протухнуть — і перезібрати їх можна тільки тим самим генератором. Тому
кожна цифра підставляється з бази або рахується моделлю back_core.py, а сам
файл лежить у репо поруч із рештою моделей ядра (back_core_face.py,
back_core_fx.py, back_core_wiring.py, back_core_place.py), а не в /tmp: із
/tmp він зникає при першій чистці, і план перетворюється на нередеровний
текст, який далі правлять руками.

Звідки числа, якщо коротко:
  · розміри, матеріали, режими ядра — lights/data/back_core.json;
  · посадка (вікно + поле) і повне ТЗ друкарю — back_core.footprint_mm()
    і back_core.print_brief(), бо це похідні, а не константи;
  · ватти, ампери, ніч — back_core.draw_from_bus();
  · повітря плайї (у тіні / на сонці) — enclosure/data/params.json → ambient
    через back_core.ambient(). Своєї копії температури база ядра не тримає:
    доти там лежало «45 °C», а 45 у проєкті означає межу СТАНЦІЇ, не повітря;
  · витримки заміру (скільки дивитись на ватметр, скільки тримати на сонці,
    з якої відстані дивитись на вікно) — lights/data/back_core.json → bench;
  · урок стрічки (прикидка 45% проти заміряних 3.6%) — lights/data/params.json
    → addressable;
  · дата воріт — data/project.json → event, дата переїзду — data/addresses.json.

Тільки stdlib: сайт збирається на CI без залежностей.
"""

